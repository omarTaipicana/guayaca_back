// Frozen schema for initial migration. Future changes require a new migration.
import { DataTypes as D, literal } from "sequelize";
const id = () => ({
  type: D.BIGINT,
  primaryKey: true,
  autoIncrement: true,
  allowNull: false,
});
const fk = (table, allowNull = false) => ({
  type: D.BIGINT,
  allowNull,
  references: { model: table, key: "id" },
  onUpdate: "CASCADE",
  onDelete: "RESTRICT",
});
const text = (opts = {}) => ({ type: D.TEXT, allowNull: false, ...opts });
const timestamp = () => ({
  type: D.DATE,
  allowNull: false,
  defaultValue: literal("CURRENT_TIMESTAMP"),
});
export const schema001 = {
  users: {
    id: id(),
    name: text(),
    email: text({ unique: true }),
    password_hash: text(),
    role: text(),
    permissions: { type: D.JSONB, allowNull: false, defaultValue: [] },
    active: { type: D.BOOLEAN, allowNull: false, defaultValue: true },
    email_verified: { type: D.BOOLEAN, allowNull: false, defaultValue: false },
    two_factor: { type: D.BOOLEAN, allowNull: false, defaultValue: false },
    session_version: { type: D.INTEGER, allowNull: false, defaultValue: 0 },
    created_at: timestamp(),
  },
  challenges: {
    id: { type: D.STRING(36), primaryKey: true, allowNull: false },
    user_id: { ...fk("users"), onDelete: "CASCADE" },
    type: text(),
    code_hash: text(),
    expires_at: { type: D.DATE, allowNull: false },
    attempts: { type: D.INTEGER, allowNull: false, defaultValue: 0 },
    used_at: { type: D.DATE },
  },
  audit: {
    id: id(),
    user_id: fk("users", true),
    action: text(),
    details: { type: D.JSONB, allowNull: false, defaultValue: {} },
    created_at: timestamp(),
  },
  vehicles: {
    id: id(),
    plate: text({ unique: true }),
    description: text({ defaultValue: "" }),
    active: { type: D.BOOLEAN, allowNull: false, defaultValue: true },
  },
  trips: {
    id: id(),
    code: { type: D.TEXT, unique: true },
    driver_id: fk("users"),
    vehicle_id: fk("vehicles"),
    status: text({ defaultValue: "creado" }),
    client: text({ defaultValue: "" }),
    origin: text({ defaultValue: "" }),
    destination: text({ defaultValue: "" }),
    amount: { type: D.DECIMAL(12, 2), allowNull: false, defaultValue: 0 },
    created_at: timestamp(),
    started_at: { type: D.DATE },
    closed_at: { type: D.DATE },
  },
  events: {
    id: id(),
    trip_id: fk("trips"),
    type: text(),
    odometer: { type: D.DECIMAL(12, 1), allowNull: false },
    latitude: { type: D.DOUBLE },
    longitude: { type: D.DOUBLE },
    accuracy: { type: D.DOUBLE },
    location_status: text({ defaultValue: "no_disponible" }),
    notes: text({ defaultValue: "" }),
    created_at: timestamp(),
  },
  expenses: {
    id: id(),
    trip_id: fk("trips"),
    type: text(),
    amount: { type: D.DECIMAL(12, 2), allowNull: false },
    notes: text({ defaultValue: "" }),
    created_at: timestamp(),
  },
  files: {
    id: id(),
    trip_id: fk("trips"),
    event_id: fk("events", true),
    expense_id: fk("expenses", true),
    category: text(),
    stored_name: text({ unique: true }),
    original_name: text(),
    mime: text(),
    bytes: { type: D.BIGINT, allowNull: false },
    created_at: timestamp(),
    deleted_at: { type: D.DATE },
  },
};
